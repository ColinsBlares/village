  const maskCount = await loadMasks();
  const ammoCount = await loadAmmunations();
  const anticheatCount = await loadAnticheat();
  const carShowCount = await loadCarShows();
  const parkingCount = await loadParkings();
  const tuningCount = await loadTuning();
  const marketCount = await loadCarMarket();
  const zoneCount = await loadWars();
  const questCount = await loadQuests();
  const farmCount = await loadFarms();
  const fisherCount = await loadFishing();
  const worldCount = await loadWorldJobs();
  const chargeCount = await loadChargeStations();
  const npcCount = await loadNpcs();
  const infoCount = await loadInfoPeds();
  const doorCount = await loadDoors();
  const markerCount = await loadMarkers();
  const bizCount = await loadBizes();
  const orderCount = await loadCarrierOrders();
